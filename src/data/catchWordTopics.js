// Helper to get active daily pool for a specific topic
// Expands the 50 base questions by dynamically rotating in bonus questions depending on the calendar day!
export function getTopicWordsForToday(topicId) {
  const topic = CATCH_WORD_TOPICS.find(t => t.id === topicId) || CATCH_WORD_TOPICS[0];
  
  // Calculate day index (changes automatically at 00:00 every day)
  const dayOffset = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  
  // Combine all base questions
  const combined = [...topic.baseWords];
  
  // Dynamically rotate in daily bonus words based on the day
  if (topic.dailyBonus && topic.dailyBonus.length > 0) {
    const bonusCount = topic.dailyBonus.length;
    // Rotate items so that every day introduces active new words
    for (let i = 0; i < bonusCount; i++) {
      const rotatedIdx = (dayOffset + i) % bonusCount;
      combined.push(topic.dailyBonus[rotatedIdx]);
    }
  }
  
  return combined;
}
